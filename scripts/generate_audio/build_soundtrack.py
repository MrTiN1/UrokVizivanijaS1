#!/usr/bin/env python3
"""Build the full episode soundtrack: original score + sound design + voices.

Reads episodes/<ep>/episode.json (scene timing, events, music moods) and
episodes/<ep>/build/voices.json (generated by generate_voices.py).

Writes:
  assets/music/<ep>_score.wav        – music stem
  assets/sfx/<ep>_fx.wav             – sound-design stem
  episodes/<ep>/build/soundtrack.wav – final mix, loudness-normalised
                                        (-14 LUFS, -1.5 dBTP, 48 kHz stereo)
"""
from __future__ import annotations

import json
import subprocess
import sys
import wave
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
import sfx  # noqa: E402
from synth import (  # noqa: E402
    SR,
    braam,
    fade,
    heartbeat,
    hp,
    impact,
    lp,
    n2m,
    pad,
    pan,
    piano,
    pluck_low,
    reverb,
    riser,
    secs,
    sine,
    strings,
    whoosh,
)

ROOT = Path(__file__).resolve().parents[2]
RNG = np.random.default_rng(11)


class Track:
    def __init__(self, dur: float):
        self.buf = np.zeros((2, secs(dur) + secs(6)), dtype=np.float32)

    def add(self, x: np.ndarray, at: float, gain: float = 1.0, p: float = 0.0):
        if x.ndim == 1:
            x = pan(x, p)
        s = secs(at)
        if s < 0:
            x = x[:, -s:]
            s = 0
        e = min(self.buf.shape[1], s + x.shape[1])
        self.buf[:, s:e] += x[:, : e - s] * gain


def m(name: str) -> int:
    return n2m(name)


def chord(names: str) -> list[int]:
    return [m(n) for n in names.split()]


# ======================= SCORE =======================
def score_tension(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    ev = sc["events"]
    drone = (sine(36.7, d + 1) * 0.5 + lp(pad([m("D2"), m("A2")], d + 1, cutoff=300), 300) * 0.8)
    T.add(reverb(fade(drone, 1.2, 1.0), 3, 0.25), t0, 0.5)
    cl = pad(chord("D3 A3 Eb4"), 6.2, cutoff=900, attack=2.5, release=1.5)
    T.add(reverb(cl, 3.5, 0.45), t0, 0.35)
    bpm = 72
    k = 0
    while t0 + 0.4 + k * 60 / bpm < t0 + ev["titleHit"] - 0.3:
        T.add(heartbeat(0.9), t0 + 0.4 + k * 60 / bpm, 0.55)
        k += 1
    T.add(reverb(riser(1.7), 2, 0.3), t0 + ev["titleHit"] - 1.7, 0.45)
    T.add(reverb(impact(4.5, 52), 4, 0.35), t0 + ev["titleHit"], 0.9)
    T.add(reverb(braam(m("D1"), 3.2), 4, 0.4), t0 + ev["titleHit"], 0.55)
    T.add(reverb(whoosh(0.65, 0.9), 1.5, 0.3), t0 + ev["whoosh"], 0.6)


def score_calm(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    bpm = 76
    beat = 60 / bpm
    bar = beat * 4
    prog = [
        ("F2", "F3 A3 C4 E4"),
        ("A2", "A3 C4 E4 G4"),
        ("D2", "D3 F3 A3 C4"),
        ("Bb1", "Bb2 D3 F3 A3"),
        ("F2", "F3 A3 C4 E4"),
        ("C2", "C3 G3 C4 E4"),
    ]
    t = 0.2
    i = 0
    rng = np.random.default_rng(3)
    while t < d - 0.6:
        root, ch = prog[i % len(prog)]
        notes = chord(ch)
        T.add(reverb(piano(m(root), 3.2, 0.45, 0.3), 2.2, 0.3), t0 + t, 0.32, -0.2)
        patt = [0, 1, 2, 3, 2, 1, 3, 2]
        for j, pi in enumerate(patt):
            tt = t + j * beat / 2
            if tt > d - 0.4:
                break
            vel = 0.35 + 0.15 * (j % 2 == 0) + rng.uniform(-0.05, 0.05)
            T.add(reverb(piano(notes[pi] + 12, 2.4, vel, 0.5), 2.2, 0.32), t0 + tt, 0.32, 0.25 * (pi - 1.5) / 1.5)
        p = pad([n for n in notes[:3]], bar + 1.2, cutoff=900, attack=0.8, release=1.2)
        T.add(reverb(p, 2.5, 0.4), t0 + t, 0.12)
        t += bar
        i += 1


def score_neutral(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    bpm = 88
    e8 = 60 / bpm / 2
    prog = [("D", "D3 F3 A3"), ("Bb", "Bb2 D3 F3"), ("G", "G2 Bb2 D3"), ("A", "A2 C#3 E3")]
    bar = e8 * 8
    t = 0.0
    i = 0
    while t < d:
        r, ch = prog[i % 4]
        root = m(r + "2") if r != "Bb" else m("Bb1")
        for j in range(8):
            tt = t + j * e8
            if tt >= d:
                break
            T.add(pluck_low(root, 0.4, 0.55 if j % 4 == 0 else 0.35), t0 + tt, 0.45)
        T.add(reverb(pad(chord(ch), bar + 1, cutoff=1100, attack=1.0), 2.5, 0.35), t0 + t, 0.22)
        if i % 2 == 1:
            T.add(reverb(piano(chord(ch)[2] + 24, 3, 0.35), 3, 0.45), t0 + t + e8 * 3, 0.22, 0.4)
        t += bar
        i += 1


def score_foreboding(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    ev = sc["events"]
    T.add(reverb(pad(chord("D2 A2 F3"), ev["accent"] + 0.5, cutoff=600, attack=2), 3, 0.4), t0, 0.32)
    notes = ["A4", "F4", "D5", "C5", "A4", "E4", "F4", "D4"]
    for k, nn in enumerate(notes):
        tt = 0.3 + k * 1.05
        if tt > ev["penStart"]:
            break
        T.add(reverb(piano(m(nn), 3.5, 0.45, 0.35), 3.5, 0.5), t0 + tt, 0.32, 0.2 * np.sin(k))
    # swell into the signature
    sw = strings(chord("D3 A3 D4 Eb4"), ev["accent"] - ev["penStart"] + 0.4, cutoff=2600, attack=1.6, release=0.2)
    T.add(reverb(sw, 3, 0.4), t0 + ev["penStart"], 0.35)
    T.add(reverb(riser(1.2, vel=0.4), 2, 0.3), t0 + ev["accent"] - 1.2, 0.35)
    T.add(reverb(impact(4.0, 46, 0.8), 4.5, 0.4), t0 + ev["accent"], 0.75)
    tail = pad(chord("Bb1 E2 D3"), d - ev["accent"] + 2, cutoff=500, attack=0.3, release=3)
    T.add(reverb(tail, 4, 0.5), t0 + ev["accent"], 0.4)


def score_cold(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    hi = strings([m("A5"), m("E6")], d + 1, cutoff=5000, attack=3, release=2)
    T.add(reverb(hi, 4, 0.55), t0, 0.12)
    low = pad([m("A1"), m("E2")], d + 1, cutoff=280, attack=2, release=2)
    T.add(reverb(low, 3, 0.3), t0, 0.4)
    tick = 60 / 96
    k = 0
    while 13.3 + k * tick < d:
        x = pluck_low(m("A2"), 0.25, 0.4)
        T.add(x, t0 + 13.3 + k * tick, 0.35 + 0.02 * k)
        k += 1
    un = strings([m("E4"), m("F4")], d - 15.2, cutoff=3000, attack=2.5, release=1.0)
    T.add(reverb(un, 3, 0.45), t0 + 15.4, 0.2)


def score_drama(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    drop = sc.get("musicDrop", {"at": 14.2, "length": 2})
    a, L = drop["at"], drop["length"]
    cello = pad([m("D2"), m("D3")], a + 0.05, cutoff=700, attack=1.5, release=0.05, detune=0.05)
    T.add(reverb(cello, 2.5, 0.35), t0, 0.4)
    k = 0
    while 0.5 + k * 1.0 < a - 0.5:
        T.add(heartbeat(0.7 + 0.02 * k), t0 + 0.5 + k * 1.0, 0.45)
        k += 1
    cl = strings(chord("A3 Bb3 D4 Eb4"), a - 6.5, cutoff=3000, attack=4, release=0.05)
    T.add(reverb(cl, 3, 0.3), t0 + 6.5, 0.22)
    # hard cut to silence at the drop (reverb tails cut too)
    T.buf[:, secs(t0 + a) : secs(t0 + a + L)] *= 0.0
    T.add(reverb(impact(5, 40, 0.7), 5, 0.5), t0 + a + L, 0.6)
    dark = pad([m("D1"), m("A1"), m("F2")], d - a - L + 3, cutoff=380, attack=0.5, release=3)
    T.add(reverb(dark, 4, 0.45), t0 + a + L, 0.42)


def score_dark(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    ev = sc["events"]
    fo0, fo1 = ev["fadeOut"]
    dr = pad([m("D1"), m("A1"), m("D2")], d + 0.5, cutoff=320, attack=1.5, release=2.5)
    T.add(reverb(dr, 4, 0.4), t0, 0.42)
    hi = strings(chord("F4 A4 D5"), fo0 + 1, cutoff=3500, attack=5, release=2)
    T.add(reverb(hi, 5, 0.6), t0 + 1, 0.12)
    k = 0
    while 1.0 + k * 60 / 54 < fo0:
        T.add(heartbeat(0.6), t0 + 1.0 + k * 60 / 54, 0.4)
        k += 1
    T.add(reverb(piano(m("D3"), 5, 0.5, 0.2), 5, 0.6), t0 + fo0 - 0.3, 0.35)


def score_tail(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    T.add(reverb(impact(5, 38, 0.9), 6, 0.5), t0 + sc["events"]["hit"], 0.75)
    ring = sine(m("D5") and 587.3, 4.5) * np.exp(-np.arange(secs(4.5)) / SR / 1.6) * 0.15
    T.add(reverb(ring, 5, 0.7), t0 + sc["events"]["hit"], 0.4)
    T.add(reverb(pad([m("D1"), m("A1")], d, cutoff=250, attack=0.2, release=3), 4, 0.4), t0, 0.35)


SCORES = {
    "tension": score_tension,
    "calm": score_calm,
    "neutral": score_neutral,
    "foreboding": score_foreboding,
    "cold": score_cold,
    "drama": score_drama,
    "dark": score_dark,
    "dark_tail": score_tail,
}


# ======================= SOUND DESIGN =======================
def walla(dur: float) -> np.ndarray:
    """Background student chatter built from real TTS phrases (indistinct)."""
    cache = ROOT / "assets" / "sfx" / "walla_college.wav"
    if cache.exists():
        x = read_mono(cache)
    else:
        sys.path.insert(0, str(Path(__file__).parent))
        from generate_voices import load_voice  # noqa
        from piper import SynthesisConfig

        phrases = [
            ("irina", "Ты домашку по сетям сделала? Я до ночи сидела."),
            ("denis", "Слушай, а во сколько пара закончится? Пойдём потом в столовую."),
            ("dmitri", "Да нормально, потом скину тебе файл."),
            ("irina", "Покажи, как ты это настроил, у меня не запускается."),
            ("ruslan", "Он опять опаздывает, как всегда."),
            ("denis", "Я вчера весь вечер с этим кодом разбирался."),
        ]
        voices_out = []
        for i, (vname, text) in enumerate(phrases):
            v = load_voice(vname)
            cfg = SynthesisConfig(length_scale=0.95, noise_scale=0.7, noise_w_scale=0.9)
            chunks = [c.audio_float_array for c in v.synthesize(text, cfg)]
            a = np.concatenate(chunks)
            from scipy.signal import resample_poly

            a = resample_poly(a, 48000, v.config.sample_rate).astype(np.float32)
            voices_out.append(a)
        total = secs(14)
        x = np.zeros(total, dtype=np.float32)
        rng = np.random.default_rng(5)
        for rep in range(3):
            for a in voices_out:
                p = rng.integers(0, total - len(a))
                x[p : p + len(a)] += a * rng.uniform(0.3, 0.7)
        x = lp(hp(x, 250), 2600)
        x = x / (np.max(np.abs(x)) + 1e-9) * 0.5
        write_wav(cache, np.stack([x, x]))
    reps = int(np.ceil(secs(dur) / len(x))) + 1
    y = np.tile(x, reps)[: secs(dur)]
    return y


def read_mono(path: Path) -> np.ndarray:
    with wave.open(str(path), "rb") as w:
        ch = w.getnchannels()
        sr = w.getframerate()
        data = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768
    if ch > 1:
        data = data.reshape(-1, ch).mean(axis=1)
    if sr != SR:
        from scipy.signal import resample_poly

        data = resample_poly(data, SR, sr).astype(np.float32)
    return data


def write_wav(path: Path, st: np.ndarray, sr: int = SR):
    path.parent.mkdir(parents=True, exist_ok=True)
    st = np.clip(st, -1, 1)
    inter = (st.T * 32767).astype(np.int16)
    with wave.open(str(path), "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(sr)
        w.writeframes(inter.tobytes())


def design(F: Track, t0: float, sc: dict):
    d = sc["duration"]
    ev = sc["events"]
    sid = sc["id"]
    if sid == "s1_hook":
        F.add(reverb(sfx.wind(d + 1, 1.0), 2, 0.2), t0, 0.7)
        F.add(sfx.fire_crackle(d), t0, 0.25, 0.4)
        F.add(reverb(sfx.distant_boom(1.0), 4, 0.5), t0 + ev["boom1"], 0.7, -0.5)
        F.add(reverb(sfx.distant_boom(0.7), 4, 0.5), t0 + ev["boom2"], 0.55, 0.6)
    elif sid == "s2_college":
        F.add(sfx.room_tone(d), t0, 0.6)
        F.add(reverb(walla(d), 1.2, 0.35), t0, 0.16)
        F.add(sfx.birds(d), t0, 0.25, 0.7)
        for a, b in ev["typing"]:
            close = 4.5 <= a < 8
            F.add(reverb(sfx.typing(b - a, 8.5), 0.8, 0.15), t0 + a, 0.55 if close else 0.3)
    elif sid == "s3_agitation":
        F.add(sfx.room_tone(d, 0.08), t0, 0.6)
        F.add(reverb(sfx.murmur(d), 2.5, 0.5), t0, 0.5)
        F.add(reverb(walla(3.0), 2.5, 0.5) * np.linspace(1, 0, secs(3.0)), t0, 0.1)
    elif sid == "s4_signing":
        F.add(sfx.room_tone(d), t0, 0.6)
        F.add(reverb(sfx.paper_slide(0.9), 0.6, 0.2), t0 + ev["paperSlide"], 0.8)
        F.add(reverb(sfx.page_flip(0.8), 0.6, 0.2), t0 + ev["paperTurn"], 0.7)
        F.add(reverb(sfx.pen_scratch(ev["penEnd"] - ev["penStart"]), 0.5, 0.15), t0 + ev["penStart"], 1.0)
    elif sid == "s5_training":
        F.add(reverb(sfx.wind(d + 1, 0.8), 2, 0.2), t0, 0.55)
        eng = np.concatenate([sfx.engine(ev["brake"], 52, 30, 1.0), sfx.engine(d - ev["brake"], 30, 30, 0.7)])
        envl = np.concatenate([np.linspace(0.2, 1, secs(2.0)), np.ones(secs(ev["brake"] - 2.0)), np.linspace(1, 0.6, secs(2)), np.full(secs(d - ev["brake"] - 2), 0.6)])
        envl = envl[: len(eng)]
        envl[secs(9.5) :] *= np.linspace(1, 0, len(envl) - secs(9.5)) ** 0.5 if len(envl) > secs(9.5) else 1
        F.add(reverb(eng[: len(envl)] * envl, 1.5, 0.2), t0, 0.75, 0.3)
        F.add(reverb(sfx.air_brake(), 1.5, 0.25), t0 + ev["brake"], 0.65, 0.3)
        F.add(reverb(sfx.door_pneumatic(), 1.2, 0.25), t0 + ev["door"], 0.7, 0.2)
        s0, s1 = ev["steps"]
        F.add(reverb(sfx.footsteps(s1 - s0, 1.9, 6), 1, 0.2), t0 + s0, 0.6)
        F.add(reverb(sfx.drill_distant(d - 9.5), 2.5, 0.4), t0 + 9.5, 0.4, -0.4)
        F.add(reverb(sfx.whistle(1.0), 2.5, 0.45), t0 + ev["whistle"], 0.35, -0.5)
        r0, r1 = ev["runSteps"]
        F.add(reverb(sfx.footsteps(r1 - r0, 3.0, 5, "hard"), 1.5, 0.3), t0 + r0, 0.4)
    elif sid == "s6_assignment":
        F.add(sfx.room_tone(d, 0.05), t0, 0.6)
        F.add(sfx.hum(d, 100, 0.006), t0, 1.0)
        for k in range(int(d)):
            F.add(reverb(sfx.clock_tick(1.0, tock=bool(k % 2)), 0.8, 0.3), t0 + 0.2 + k, 0.35, 0.5)
        for tt in ev["pageFlip"]:
            F.add(reverb(sfx.page_flip(0.7), 0.7, 0.25), t0 + tt, 0.55, 0.2)
        F.add(reverb(sfx.folder_close(1.0), 0.8, 0.3), t0 + ev["folderClose"], 0.8)
    elif sid == "s7_transport":
        tr = sfx.truck_interior(d + 1)
        e = np.ones(len(tr))
        f0, f1 = ev["fadeOut"]
        a, b = secs(f0), secs(f1)
        e[a:b] = np.linspace(1, 0.15, b - a)
        e[b:] = 0.15
        F.add(reverb(tr * e, 0.6, 0.15), t0, 0.7)
        for tt in ev["boom"]:
            F.add(reverb(lp(sfx.distant_boom(0.8), 120), 4, 0.5), t0 + tt, 0.6, 0.4)
    elif sid == "s8_end":
        F.add(reverb(sfx.wind(d, 0.4), 2, 0.3) * np.linspace(1, 0, secs(d)), t0, 0.45)


# ======================= MIX =======================
def main():
    ep_name = sys.argv[1] if len(sys.argv) > 1 else "episode_01"
    ep_dir = ROOT / "episodes" / ep_name
    ep = json.loads((ep_dir / "episode.json").read_text(encoding="utf-8"))
    voices = json.loads((ep_dir / "build" / "voices.json").read_text(encoding="utf-8"))
    D = ep["duration"]
    M, F, V = Track(D), Track(D), Track(D)
    voice_env = np.zeros(M.buf.shape[1], dtype=np.float32)

    for sc in ep["scenes"]:
        t0 = sc["start"]
        print(f"scene {sc['id']} @ {t0}s music={sc['music']}")
        sub = Track(sc["duration"] + 4)
        SCORES[sc["music"]](sub, 0.0, sc)
        # crossfade scene music edges
        n = secs(sc["duration"])
        sub.buf[:, n + secs(1.2) :] = 0
        sub.buf[:, n : n + secs(1.2)] *= np.linspace(1, 0, secs(1.2))
        M.add(sub.buf, t0)
        design(F, t0, sc)
        for line in sc["lines"]:
            info = voices[line["id"]]
            x = read_mono(ROOT / "assets" / info["file"])
            at = t0 + line["at"]
            spk = line["speaker"]
            if spk == "narrator":
                V.add(x, at, 1.0)
            else:
                room = {"s3_agitation": (1.6, 0.18), "s6_assignment": (0.7, 0.14), "s5_training": (1.0, 0.08)}.get(sc["id"], (0.6, 0.08))
                V.add(reverb(x, room[0], room[1]), at, 1.0)
            s = secs(at)
            voice_env[s : s + len(x)] = np.maximum(voice_env[s : s + len(x)], (np.abs(x) > 0.01).astype(np.float32))

    # smooth voice presence → ducking gain
    from scipy.ndimage import maximum_filter1d, uniform_filter1d

    pres = maximum_filter1d(voice_env, secs(0.35))
    pres = uniform_filter1d(pres, secs(0.25))
    duck_m = 1 - 0.62 * pres  # ≈ -8.4 dB
    duck_f = 1 - 0.38 * pres
    music = M.buf * duck_m
    fxs = F.buf * duck_f
    end = secs(D)
    mix = music * 0.9 + fxs * 0.85 + V.buf * 1.0
    mix = mix[:, :end]
    mix[:, -secs(0.6) :] *= np.linspace(1, 0, secs(0.6))
    # gentle bus glue
    peak = np.max(np.abs(mix))
    mix = np.tanh(mix / max(peak, 1e-6) * 1.2) * 0.8

    write_wav(ROOT / "assets" / "music" / f"{ep_name}_score.wav", np.clip(music[:, :end] * 0.5, -1, 1))
    write_wav(ROOT / "assets" / "sfx" / f"{ep_name}_fx.wav", np.clip(fxs[:, :end] * 0.5, -1, 1))
    raw = ROOT / "output" / "tmp" / f"{ep_name}_mix_raw.wav"
    write_wav(raw, mix)
    out = ep_dir / "build" / "soundtrack.wav"
    # two-pass loudness normalisation for Shorts/TikTok (-14 LUFS)
    r = subprocess.run(
        ["ffmpeg", "-hide_banner", "-i", str(raw), "-af", "loudnorm=I=-14:TP=-1.5:LRA=11:print_format=json", "-f", "null", "-"],
        stderr=subprocess.PIPE,
        text=True,
    )
    js = r.stderr[r.stderr.rfind("{") : r.stderr.rfind("}") + 1]
    st = json.loads(js)
    af = (
        f"loudnorm=I=-14:TP=-1.5:LRA=11:measured_I={st['input_i']}:measured_TP={st['input_tp']}:"
        f"measured_LRA={st['input_lra']}:measured_thresh={st['input_thresh']}:offset={st['target_offset']}:linear=true"
    )
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(raw), "-af", af, "-ar", "48000", str(out)], check=True)
    print(f"wrote {out}  (input I={st['input_i']} LUFS)")


if __name__ == "__main__":
    main()
