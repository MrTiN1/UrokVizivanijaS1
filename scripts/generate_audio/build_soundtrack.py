def design_generic(F: Track, t0: float, sc: dict):
    """Data-driven sound design: episode.json ambience [[name, gain]], sfx [[t, name, gain]], steps [[a, b, rate, surface]]."""
    d = sc["duration"]
    for name, gain in sc.get("ambience", []):
        x = AMBIENCE[name](d + 1.0)
        n = len(x)
        x = x * np.minimum(1, np.arange(n) / secs(0.4)) * np.minimum(1, (n - np.arange(n)) / secs(0.6))
        F.add(x, t0, gain)
    for item in sc.get("sfx", []):
        tt, name = item[0], item[1]
        gain = item[2] if len(item) > 2 else 0.6
        F.add(reverb(ONESHOTS[name](), 1.0, 0.2), t0 + tt, gain)
    for a, b, rate, surface in sc.get("steps", []):
        x = sfx.footsteps_wet(b - a, rate) if surface == "wet" else sfx.footsteps(b - a, rate, 1, "hard")
        F.add(reverb(x, 0.8, 0.2), t0 + a, 0.5)


def design(F: Track, t0: float, sc: dict):
    d = sc["duration"]
    ev = sc["events"]
    sid = sc["id"]
    if "sfx" in sc or (sc.get("ambience") and isinstance(sc["ambience"][0], list)):
        design_generic(F, t0, sc)
        return
    if sid == "s1_hook":
        F.add(reverb(sfx.wind(d + 1, 1.0), 2, 0.2), t0, 0.7)
        F.add(sfx.fire_crackle(d), t0, 0.25, 0.4)
        F.add(reverb(sfx.distant_boom(1.0), 4, 0.5), t0 + ev["boom1"], 0.7, -0.5)
        F.add(reverb(sfx.distant_boom(0.7), 4, 0.5), t0 + ev["boom2"], 0.55, 0.6)
    elif sid == "s2_college":
        F.add(sfx.room_tone(d), t0, 0.6)
        F.add(reverb(walla(d), 1.2, 0.35), t0, 0.16)
        F.add(sfx.birds(d), t0, 0.25, 0.7)
        for a, b in ev["typing"]:
            close = 4.5 <= a < 8
            F.add(reverb(sfx.typing(b - a, 8.5), 0.8, 0.15), t0 + a, 0.55 if close else 0.3)
    elif sid == "s3_agitation":
        F.add(sfx.room_tone(d, 0.08), t0, 0.6)
        F.add(reverb(sfx.murmur(d), 2.5, 0.5), t0, 0.5)
        F.add(reverb(walla(3.0), 2.5, 0.5) * np.linspace(1, 0, secs(3.0)), t0, 0.1)
    elif sid == "s4_signing":
        F.add(sfx.room_tone(d), t0, 0.6)
        F.add(reverb(sfx.paper_slide(0.9), 0.6, 0.2), t0 + ev["paperSlide"], 0.8)
        F.add(reverb(sfx.page_flip(0.8), 0.6, 0.2), t0 + ev["paperTurn"], 0.7)
        F.add(reverb(sfx.pen_scratch(ev["penEnd"] - ev["penStart"]), 0.5, 0.15), t0 + ev["penStart"], 1.0)
    elif sid == "s5_training":
        F.add(reverb(sfx.wind(d + 1, 0.8), 2, 0.2), t0, 0.55)
        eng = np.concatenate([sfx.engine(ev["brake"], 52, 30, 1.0), sfx.engine(d - ev["brake"], 30, 30, 0.7)])
        envl = np.concatenate([np.linspace(0.2, 1, secs(2.0)), np.ones(secs(ev["brake"] - 2.0)), np.linspace(1, 0.6, secs(2)), np.full(secs(d - ev["brake"] - 2), 0.6)])
        envl = envl[: len(eng)]
        envl[secs(9.5) :] *= np.linspace(1, 0, len(envl) - secs(9.5)) ** 0.5 if len(envl) > secs(9.5) else 1
        F.add(reverb(eng[: len(envl)] * envl, 1.5, 0.2), t0, 0.75, 0.3)
        F.add(reverb(sfx.air_brake(), 1.5, 0.25), t0 + ev["brake"], 0.65, 0.3)
        F.add(reverb(sfx.door_pneumatic(), 1.2, 0.25), t0 + ev["door"], 0.7, 0.2)
        s0, s1 = ev["steps"]
        F.add(reverb(sfx.footsteps(s1 - s0, 1.9, 6), 1, 0.2), t0 + s0, 0.6)
        F.add(reverb(sfx.drill_distant(d - 9.5), 2.5, 0.4), t0 + 9.5, 0.4, -0.4)
        F.add(reverb(sfx.whistle(1.0), 2.5, 0.45), t0 + ev["whistle"], 0.35, -0.5)
        r0, r1 = ev["runSteps"]
        F.add(reverb(sfx.footsteps(r1 - r0, 3.0, 5, "hard"), 1.5, 0.3), t0 + r0, 0.4)
    elif sid == "s6_assignment":
        F.add(sfx.room_tone(d, 0.05), t0, 0.6)
        F.add(sfx.hum(d, 100, 0.006), t0, 1.0)
        for k in range(int(d)):
            F.add(reverb(sfx.clock_tick(1.0, tock=bool(k % 2)), 0.8, 0.3), t0 + 0.2 + k, 0.35, 0.5)
        for tt in ev["pageFlip"]:
            F.add(reverb(sfx.page_flip(0.7), 0.7, 0.25), t0 + tt, 0.55, 0.2)
        F.add(reverb(sfx.folder_close(1.0), 0.8, 0.3), t0 + ev["folderClose"], 0.8)
    elif sid == "s7_transport":
        tr = sfx.truck_interior(d + 1)
        e = np.ones(len(tr))
        f0, f1 = ev["fadeOut"]
        a, b = secs(f0), secs(f1)
        e[a:b] = np.linspace(1, 0.15, b - a)
        e[b:] = 0.15
        F.add(reverb(tr * e, 0.6, 0.15), t0, 0.7)
        for tt in ev["boom"]:
            F.add(reverb(lp(sfx.distant_boom(0.8), 120), 4, 0.5), t0 + tt, 0.6, 0.4)
    elif sid == "s8_end":
        F.add(reverb(sfx.wind(d, 0.4), 2, 0.3) * np.linspace(1, 0, secs(d)), t0, 0.45)


