def main():
    ep_name = sys.argv[1] if len(sys.argv) > 1 else "episode_01"
    ep_dir = ROOT / "episodes" / ep_name
    ep = json.loads((ep_dir / "episode.json").read_text(encoding="utf-8"))
    voices = json.loads((ep_dir / "build" / "voices.json").read_text(encoding="utf-8"))
    D = ep["duration"]
    M, F, V = Track(D), Track(D), Track(D)
    voice_env = np.zeros(M.buf.shape[1], dtype=np.float32)

    for sc in ep["scenes"]:
        t0 = sc["start"]
        print(f"scene {sc['id']} @ {t0}s music={sc['music']}")
        sub = Track(sc["duration"] + 4)
        SCORES[sc["music"]](sub, 0.0, sc)
        # crossfade scene music edges
        n = secs(sc["duration"])
        sub.buf[:, n + secs(1.2) :] = 0
        sub.buf[:, n : n + secs(1.2)] *= np.linspace(1, 0, secs(1.2))
        M.add(sub.buf, t0)
        design(F, t0, sc)
        for line in sc["lines"]:
            info = voices[line["id"]]
            x = read_mono(ROOT / "assets" / info["file"])
            at = t0 + line["at"]
            spk = line["speaker"]
            lg = line.get("gain", 1.0)  # per-line level trim (episode.json)
            if spk == "narrator":
                V.add(x, at, lg)
            else:
                room = {"s3_agitation": (1.6, 0.18), "s6_assignment": (0.7, 0.14), "s5_training": (1.0, 0.08)}.get(sc["id"], (0.6, 0.08))
                V.add(reverb(x, room[0], room[1]), at, lg)
            s = secs(at)
            voice_env[s : s + len(x)] = np.maximum(voice_env[s : s + len(x)], (np.abs(x) > 0.01).astype(np.float32))

    # smooth voice presence → ducking gain
    from scipy.ndimage import maximum_filter1d, uniform_filter1d

    pres = maximum_filter1d(voice_env, secs(0.35))
    pres = uniform_filter1d(pres, secs(0.25))
    duck_m = 1 - 0.7 * pres  # ≈ -10.5 dB
    duck_f = 1 - 0.38 * pres
    music = M.buf * duck_m
    fxs = F.buf * duck_f
    banner = ep.get("banner") or {}
    if banner.get("enabled"):
        # bed almost silent under the sponsor banner so its own (unchanged) sound is clear
        a = secs(banner["at"])
        b = secs(banner["at"] + banner["duration"] / banner.get("speed", 1.0))
        g = np.ones(music.shape[1], dtype=np.float32)
        f_ = secs(0.35)
        g[a:b] = 0.05
        g[a - f_ : a] = np.linspace(1, 0.05, f_)
        g[b : b + f_] = np.linspace(0.05, 1, f_)
        music = music * g
        fxs = fxs * g
    end = secs(D)
    mix = music * 0.9 + fxs * 0.85 + V.buf * 1.0
    mix = mix[:, :end]
    mix[:, -secs(0.6) :] *= np.linspace(1, 0, secs(0.6))
    # gentle bus glue
    peak = np.max(np.abs(mix))
    mix = np.tanh(mix / max(peak, 1e-6) * 1.2) * 0.8

    write_wav(ROOT / "assets" / "music" / f"{ep_name}_score.wav", np.clip(music[:, :end] * 0.5, -1, 1))
    write_wav(ROOT / "assets" / "sfx" / f"{ep_name}_fx.wav", np.clip(fxs[:, :end] * 0.5, -1, 1))
    raw = ROOT / "output" / "tmp" / f"{ep_name}_mix_raw.wav"
    write_wav(raw, mix)
    out = ep_dir / "build" / "soundtrack.wav"
    # two-pass loudness normalisation for Shorts/TikTok (-14 LUFS)
    r = subprocess.run(
        ["ffmpeg", "-hide_banner", "-i", str(raw), "-af", "loudnorm=I=-14:TP=-2.2:LRA=11:print_format=json", "-f", "null", "-"],
        stderr=subprocess.PIPE,
        text=True,
    )
    js = r.stderr[r.stderr.rfind("{") : r.stderr.rfind("}") + 1]
    st = json.loads(js)
    af = (
        f"loudnorm=I=-14:TP=-2.2:LRA=11:measured_I={st['input_i']}:measured_TP={st['input_tp']}:"
        f"measured_LRA={st['input_lra']}:measured_thresh={st['input_thresh']}:offset={st['target_offset']}:linear=true"
    )
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-i", str(raw), "-af", af, "-ar", "48000", str(out)], check=True)
    if banner.get("enabled") and banner.get("audioMode", "original") == "original":
        # the banner's own sound, sample-for-sample unchanged (no gain, no EQ, no normalisation)
        with wave.open(str(out)) as w:
            sr = w.getframerate()
            base = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).reshape(-1, 2).astype(np.int32)
        with wave.open(str(ROOT / "assets" / banner["audio"])) as w:
            assert w.getframerate() == sr and w.getnchannels() == 2
            bn = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).reshape(-1, 2).astype(np.int32)
        s0 = int(round(banner["at"] * sr))
        e0 = min(len(base), s0 + len(bn))
        base[s0:e0] += bn[: e0 - s0]
        base = np.clip(base, -32768, 32767).astype(np.int16)
        with wave.open(str(out), "wb") as w:
            w.setnchannels(2)
            w.setsampwidth(2)
            w.setframerate(sr)
            w.writeframes(base.tobytes())
        print(f"banner audio inserted unchanged at {banner['at']}s")
    print(f"wrote {out}  (input I={st['input_i']} LUFS)")


if __name__ == "__main__":
    main()
