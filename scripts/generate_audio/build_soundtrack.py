def score_tension(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    ev = sc["events"]
    drone = (sine(36.7, d + 1) * 0.5 + lp(pad([m("D2"), m("A2")], d + 1, cutoff=300), 300) * 0.8)
    T.add(reverb(fade(drone, 1.2, 1.0), 3, 0.25), t0, 0.5)
    cl = pad(chord("D3 A3 Eb4"), 6.2, cutoff=900, attack=2.5, release=1.5)
    T.add(reverb(cl, 3.5, 0.45), t0, 0.35)
    bpm = 72
    k = 0
    while t0 + 0.4 + k * 60 / bpm < t0 + ev["titleHit"] - 0.3:
        T.add(heartbeat(0.9), t0 + 0.4 + k * 60 / bpm, 0.55)
        k += 1
    T.add(reverb(riser(1.7), 2, 0.3), t0 + ev["titleHit"] - 1.7, 0.45)
    T.add(reverb(impact(4.5, 52), 4, 0.35), t0 + ev["titleHit"], 0.9)
    T.add(reverb(braam(m("D1"), 3.2), 4, 0.4), t0 + ev["titleHit"], 0.55)
    T.add(reverb(whoosh(0.65, 0.9), 1.5, 0.3), t0 + ev["whoosh"], 0.6)


def score_calm(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    bpm = 76
    beat = 60 / bpm
    bar = beat * 4
    prog = [
        ("F2", "F3 A3 C4 E4"),
        ("A2", "A3 C4 E4 G4"),
        ("D2", "D3 F3 A3 C4"),
        ("Bb1", "Bb2 D3 F3 A3"),
        ("F2", "F3 A3 C4 E4"),
        ("C2", "C3 G3 C4 E4"),
    ]
    t = 0.2
    i = 0
    rng = np.random.default_rng(3)
    while t < d - 0.6:
        root, ch = prog[i % len(prog)]
        notes = chord(ch)
        T.add(reverb(piano(m(root), 3.2, 0.45, 0.3), 2.2, 0.3), t0 + t, 0.32, -0.2)
        patt = [0, 1, 2, 3, 2, 1, 3, 2]
        for j, pi in enumerate(patt):
            tt = t + j * beat / 2
            if tt > d - 0.4:
                break
            vel = 0.35 + 0.15 * (j % 2 == 0) + rng.uniform(-0.05, 0.05)
            T.add(reverb(piano(notes[pi] + 12, 2.4, vel, 0.5), 2.2, 0.32), t0 + tt, 0.32, 0.25 * (pi - 1.5) / 1.5)
        p = pad([n for n in notes[:3]], bar + 1.2, cutoff=900, attack=0.8, release=1.2)
        T.add(reverb(p, 2.5, 0.4), t0 + t, 0.12)
        t += bar
        i += 1


def score_neutral(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    bpm = 88
    e8 = 60 / bpm / 2
    prog = [("D", "D3 F3 A3"), ("Bb", "Bb2 D3 F3"), ("G", "G2 Bb2 D3"), ("A", "A2 C#3 E3")]
    bar = e8 * 8
    t = 0.0
    i = 0
    while t < d:
        r, ch = prog[i % 4]
        root = m(r + "2") if r != "Bb" else m("Bb1")
        for j in range(8):
            tt = t + j * e8
            if tt >= d:
                break
            T.add(pluck_low(root, 0.4, 0.55 if j % 4 == 0 else 0.35), t0 + tt, 0.45)
        T.add(reverb(pad(chord(ch), bar + 1, cutoff=1100, attack=1.0), 2.5, 0.35), t0 + t, 0.22)
        if i % 2 == 1:
            T.add(reverb(piano(chord(ch)[2] + 24, 3, 0.35), 3, 0.45), t0 + t + e8 * 3, 0.22, 0.4)
        t += bar
        i += 1


def score_foreboding(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    ev = sc["events"]
    T.add(reverb(pad(chord("D2 A2 F3"), ev["accent"] + 0.5, cutoff=600, attack=2), 3, 0.4), t0, 0.32)
    notes = ["A4", "F4", "D5", "C5", "A4", "E4", "F4", "D4"]
    for k, nn in enumerate(notes):
        tt = 0.3 + k * 1.05
        if tt > ev["penStart"]:
            break
        T.add(reverb(piano(m(nn), 3.5, 0.45, 0.35), 3.5, 0.5), t0 + tt, 0.32, 0.2 * np.sin(k))
    # swell into the signature
    sw = strings(chord("D3 A3 D4 Eb4"), ev["accent"] - ev["penStart"] + 0.4, cutoff=2600, attack=1.6, release=0.2)
    T.add(reverb(sw, 3, 0.4), t0 + ev["penStart"], 0.35)
    T.add(reverb(riser(1.2, vel=0.4), 2, 0.3), t0 + ev["accent"] - 1.2, 0.35)
    T.add(reverb(impact(4.0, 46, 0.8), 4.5, 0.4), t0 + ev["accent"], 0.75)
    tail = pad(chord("Bb1 E2 D3"), d - ev["accent"] + 2, cutoff=500, attack=0.3, release=3)
    T.add(reverb(tail, 4, 0.5), t0 + ev["accent"], 0.4)


def score_cold(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    hi = strings([m("A5"), m("E6")], d + 1, cutoff=5000, attack=3, release=2)
    T.add(reverb(hi, 4, 0.55), t0, 0.12)
    low = pad([m("A1"), m("E2")], d + 1, cutoff=280, attack=2, release=2)
    T.add(reverb(low, 3, 0.3), t0, 0.4)
    tick = 60 / 96
    k = 0
    while 13.3 + k * tick < d:
        x = pluck_low(m("A2"), 0.25, 0.4)
        T.add(x, t0 + 13.3 + k * tick, 0.35 + 0.02 * k)
        k += 1
    un = strings([m("E4"), m("F4")], d - 15.2, cutoff=3000, attack=2.5, release=1.0)
    T.add(reverb(un, 3, 0.45), t0 + 15.4, 0.2)


def score_drama(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    drop = sc.get("musicDrop", {"at": 14.2, "length": 2})
    a, L = drop["at"], drop["length"]
    cello = pad([m("D2"), m("D3")], a + 0.05, cutoff=700, attack=1.5, release=0.05, detune=0.05)
    T.add(reverb(cello, 2.5, 0.35), t0, 0.4)
    k = 0
    while 0.5 + k * 1.0 < a - 0.5:
        T.add(heartbeat(0.7 + 0.02 * k), t0 + 0.5 + k * 1.0, 0.45)
        k += 1
    if a > 7.5:  # rising cluster only when the drop comes late in the scene
        cl = strings(chord("A3 Bb3 D4 Eb4"), a - 6.5, cutoff=3000, attack=4, release=0.05)
        T.add(reverb(cl, 3, 0.3), t0 + 6.5, 0.22)
    # hard cut to silence at the drop (reverb tails cut too)
    T.buf[:, secs(t0 + a) : secs(t0 + a + L)] *= 0.0
    T.add(reverb(impact(5, 40, 0.7), 5, 0.5), t0 + a + L, 0.6)
    dark = pad([m("D1"), m("A1"), m("F2")], d - a - L + 3, cutoff=380, attack=0.5, release=3)
    T.add(reverb(dark, 4, 0.45), t0 + a + L, 0.42)


def score_dark(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    ev = sc["events"]
    fo0, fo1 = ev["fadeOut"]
    dr = pad([m("D1"), m("A1"), m("D2")], d + 0.5, cutoff=320, attack=1.5, release=2.5)
    T.add(reverb(dr, 4, 0.4), t0, 0.42)
    hi = strings(chord("F4 A4 D5"), fo0 + 1, cutoff=3500, attack=5, release=2)
    T.add(reverb(hi, 5, 0.6), t0 + 1, 0.12)
    k = 0
    while 1.0 + k * 60 / 54 < fo0:
        T.add(heartbeat(0.6), t0 + 1.0 + k * 60 / 54, 0.4)
        k += 1
    T.add(reverb(piano(m("D3"), 5, 0.5, 0.2), 5, 0.6), t0 + fo0 - 0.3, 0.35)


def score_tail(T: Track, t0: float, sc: dict):
    d = sc["duration"]
    T.add(reverb(impact(5, 38, 0.9), 6, 0.5), t0 + sc["events"]["hit"], 0.75)
    ring = sine(m("D5") and 587.3, 4.5) * np.exp(-np.arange(secs(4.5)) / SR / 1.6) * 0.15
    T.add(reverb(ring, 5, 0.7), t0 + sc["events"]["hit"], 0.4)
    T.add(reverb(pad([m("D1"), m("A1")], d, cutoff=250, attack=0.2, release=3), 4, 0.4), t0, 0.35)


