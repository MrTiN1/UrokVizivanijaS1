#!/usr/bin/env python3
"""Point the Remotion project at an episode folder: writes src/current_episode.ts.

  set_episode.py episode_01
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ep = sys.argv[1] if len(sys.argv) > 1 else "episode_01"
if not (ROOT / "episodes" / ep / "episode.json").exists():
    raise SystemExit(f"no episodes/{ep}/episode.json")
build = ROOT / "episodes" / ep / "build"
build.mkdir(parents=True, exist_ok=True)
for name, empty in (("voices.json", "{}"), ("subtitles.json", "[]")):
    if not (build / name).exists():
        (build / name).write_text(empty)
(ROOT / "src" / "current_episode.ts").write_text(
    "// Generated by scripts/set_episode.py — which episode the project renders.\n"
    f"import episode from '../episodes/{ep}/episode.json';\n"
    f"import voices from '../episodes/{ep}/build/voices.json';\n"
    f"import subtitles from '../episodes/{ep}/build/subtitles.json';\n\n"
    "export {episode, voices, subtitles};\n"
)
print(f"current episode: {ep}")
